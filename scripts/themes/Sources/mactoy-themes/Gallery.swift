import Foundation
import MactoyKit

/// Catalog text goes into a Markdown table cell, an HTML attribute and a link, and the
/// catalog allows `| [ ] < > * _` and backticks in names, so each place needs its own escaping.
/// Without it a name could split the table or add a link to the page.
enum GalleryText {
    /// Control characters would end the table row; a space keeps the words apart.
    private static func plain(_ s: String) -> String {
        String(String.UnicodeScalarView(s.unicodeScalars.map { $0.properties.generalCategory == .control ? " " : $0 }))
    }

    /// Visible text in a table cell: every character with Markdown meaning gets a backslash.
    static func markdown(_ s: String) -> String {
        var out = ""
        for scalar in plain(s).unicodeScalars {
            if "\\|[]<>*_`&".unicodeScalars.contains(scalar) { out.append("\\") }
            out.unicodeScalars.append(scalar)
        }
        return out
    }

    /// Inside a double-quoted HTML attribute. A backslash-escaped `|` would still be an HTML
    /// attribute character, so entities are used: they survive table splitting and decode in the browser.
    static func attribute(_ s: String) -> String {
        var out = ""
        for scalar in plain(s).unicodeScalars {
            switch scalar {
            case "&": out += "&amp;"
            case "<": out += "&lt;"
            case ">": out += "&gt;"
            case "\"": out += "&quot;"
            case "'": out += "&#39;"
            case "|": out += "&#124;"
            case "`": out += "&#96;"
            default: out.unicodeScalars.append(scalar)
            }
        }
        return out
    }

    /// A link target: `(`, `)`, spaces and the characters that end or break a Markdown link or cell are percent-encoded.
    static func destination(_ url: URL) -> String {
        var out = ""
        for scalar in url.absoluteString.unicodeScalars {
            if "() <>\"|`\\".unicodeScalars.contains(scalar) || scalar.properties.generalCategory == .control {
                out += scalar.utf8.map { String(format: "%%%02X", $0) }.joined()
            } else {
                out.unicodeScalars.append(scalar)
            }
        }
        return out
    }

    /// A preview file name from an id (catalog ids are `[a-z0-9-]`, but this isn't the place to rely on that).
    static func previewSource(id: String) -> String {
        attribute("previews/" + (id.addingPercentEncoding(withAllowedCharacters: .alphanumerics.union(CharacterSet(charactersIn: "-._~"))) ?? "") + ".jpg")
    }
}

func galleryMarkdown(_ catalog: ThemeCatalog) -> String {
    var md = """
    # Boot menu themes

    <!-- Generated by `swift run --package-path scripts/themes mactoy-themes gallery themes/catalog.json themes/README.md`. Don't edit by hand. -->

    Mactoy can add any of these to a Ventoy drive, from **Install Ventoy** or **Manage Disk**. Each screenshot is the theme booted in Ventoy. Mactoy downloads themes from their authors, checks each download against the checksum in [`catalog.json`](catalog.json), and copies only image, font and theme files to your drive.

    Want to add one? See [Adding a boot theme](../CONTRIBUTING.md#adding-a-boot-theme).

    | | |
    |---|---|

    """
    let cells = catalog.themes.map { t -> String in
        let keys = t.showsVentoyHotkeys ? "F1–F6 key bar" : "no Ventoy key bar"
        // Only an https homepage becomes a link.
        let author = t.homepage.scheme == "https"
            ? "[\(GalleryText.markdown(t.author))](\(GalleryText.destination(t.homepage)))"
            : GalleryText.markdown(t.author)
        return "<img src=\"\(GalleryText.previewSource(id: t.id))\" width=\"420\" alt=\"\(GalleryText.attribute(t.name))\"><br>**\(GalleryText.markdown(t.name))** by \(author) · \(GalleryText.markdown(t.license)) · \(keys)"
    }
    stride(from: 0, to: cells.count, by: 2).forEach { i in
        md += "| \(cells[i]) | \(i + 1 < cells.count ? cells[i + 1] : "") |\n"
    }
    return md
}
